"""Shared Alembic runner: each service's `alembic/env.py` calls `run_migrations(...)`."""

from collections.abc import Callable
from logging.config import fileConfig
from typing import Any

from alembic import context
from sqlalchemy import MetaData, engine_from_config, pool


def _only_own_tables(
    obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
) -> bool:
    """Ignore tables that exist in the database but not in the service's models.

    The PostGIS image ships extra tables (e.g. `spatial_ref_sys`, the tiger geocoder); an
    autogenerated migration must never drop them.
    """
    return not (type_ == "table" and reflected and compare_to is None)


def run_migrations(
    metadata: MetaData,
    database_url: Callable[[], str],
    *,
    include_object: Callable[..., bool] | None = None,
    **options: Any,
) -> None:
    config = context.config
    if config.config_file_name is not None:
        fileConfig(config.config_file_name, disable_existing_loggers=False)

    # An explicit URL (e.g. set by the test suite) wins over the service settings.
    if not config.get_main_option("sqlalchemy.url"):
        config.set_main_option("sqlalchemy.url", database_url())

    def combined_include(
        obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
    ) -> bool:
        if not _only_own_tables(obj, name, type_, reflected, compare_to):
            return False
        return include_object(obj, name, type_, reflected, compare_to) if include_object else True

    context_options = {
        "target_metadata": metadata,
        "include_object": combined_include,
        "compare_type": True,
        **options,
    }

    if context.is_offline_mode():
        context.configure(
            url=config.get_main_option("sqlalchemy.url"),
            literal_binds=True,
            dialect_opts={"paramstyle": "named"},
            **context_options,
        )
        with context.begin_transaction():
            context.run_migrations()
        return

    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, **context_options)
        with context.begin_transaction():
            context.run_migrations()
